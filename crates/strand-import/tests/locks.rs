#[test]
fn detect_format_by_filename() {
    use std::path::Path;
    assert_eq!(
        strand_import::detect_format(Path::new("Cargo.lock"), ""),
        Format::CargoLock
    );
    assert_eq!(
        strand_import::detect_format(Path::new("package-lock.json"), ""),
        Format::NpmLock
    );
    assert_eq!(
        strand_import::detect_format(Path::new("poetry.lock"), ""),
        Format::PoetryLock
    );
    assert_eq!(
        strand_import::detect_format(Path::new("go.mod"), ""),
        Format::GoMod
    );
    assert_eq!(
        strand_import::detect_format(Path::new("pom.xml"), ""),
        Format::Pom
    );
    // Content sniff for renamed files.
    assert_eq!(
        strand_import::detect_format(Path::new("foo.txt"), "module example.com/x\n"),
        Format::GoMod
    );
    assert_eq!(
        strand_import::detect_format(
            Path::new("foo.txt"),
            "{\"lockfileVersion\": 3, \"packages\": {}}"
        ),
        Format::NpmLock
    );
}

#[test]
fn yarn_lock_transitive() {
    let text = r#"# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


"@babel/highlight@^7.10.4":
  version "7.10.4"
  resolved "https://x"

"abbrev@1":
  version "1.1.1"
  resolved "https://x"

"left-pad@^1.3.0":
  version "1.3.0"
  resolved "https://x"
  dependencies:
    abbrev "1"

"my-app@^1.0.0", "my-app@^1.2.0":
  version "1.2.0"
  resolved "https://x"
  dependencies:
    "@babel/highlight" "^7.10.4"
    left-pad "^1.3.0"
"#;
    let e = edges(text, Format::YarnLock);
    // my-app@1.2.0 -> highlight, left-pad; left-pad -> abbrev.
    assert!(e.contains(&("my-app@1.2.0".into(), "@babel/highlight@7.10.4".into())));
    assert!(e.contains(&("my-app@1.2.0".into(), "left-pad@1.3.0".into())));
    assert!(e.contains(&("left-pad@1.3.0".into(), "abbrev@1.1.1".into())));
    // Transitive depth: highlight has no deps, abbrev none.
    assert_eq!(e.len(), 3);
}

