//! Tests for lockfile/manifest importers (locks.rs).

use strand_import::Format;

fn edges(text: &str, f: Format) -> Vec<(String, String)> {
    let mut v: Vec<(String, String)> = strand_import::parse(text, f)
        .unwrap()
        .into_iter()
        // Self-loops are node declarations, not dependency edges.
        .filter(|(a, b, ..)| a != b)
        .map(|(a, b, ..)| (a, b))
        .collect();
    v.sort();
    v
}

#[test]
fn cargo_lock_basic() {
    let text = r#"# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "liba",
 "libb 2.0.0 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "liba"
version = "1.0.0"

[[package]]
name = "libb"
version = "2.0.0"
"#;
    assert_eq!(
        edges(text, Format::CargoLock),
        vec![
            ("app@0.1.0".to_string(), "liba@1.0.0".to_string()),
            ("app@0.1.0".to_string(), "libb@2.0.0".to_string()),
        ]
    );
}

