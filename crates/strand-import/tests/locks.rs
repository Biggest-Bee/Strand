//! Tests for lockfile/manifest importers (locks.rs).

use strand_import::Format;

fn edges(text: &str, f: Format) -> Vec<(String, String)> {
    let mut v: Vec<(String, String)> = strand_import::parse(text, f)
        .unwrap()
        .into_iter()
        .map(|(a, b, ..)| (a, b))
        .collect();
    v.sort();
    v
}

#[test]
fn cargo_lock_basic() {
    let text = r#"# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "liba",
 "libb 2.0.0 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "liba"
version = "1.0.0"

[[package]]
name = "libb"
version = "2.0.0"
"#;
    assert_eq!(
        edges(text, Format::CargoLock),
        vec![
            ("app".to_string(), "liba".to_string()),
            ("app".to_string(), "libb".to_string()),
        ]
    );
}

#[test]
fn cargo_lock_single_line_deps() {
    let text = r#"[[package]]
name = "a"
version = "1"
dependencies = ["b", "c 1.0"]

[[package]]
name = "b"
version = "1"
"#;
    assert_eq!(
        edges(text, Format::CargoLock),
        vec![
            ("a".to_string(), "b".to_string()),
            ("a".to_string(), "c".to_string()),
        ]
    );
}

#[test]
fn poetry_lock_deps_and_dev_deps() {
    let text = r#"# This file is automatically @generated by Poetry.
[[package]]
name = "app"
version = "0.1.0"

[package.dependencies]
python = "^3.9"
liba = "^1.0"
libb = {version = "^2.0", extras = ["x"]}
libc = [
    {version = "^3.0", markers = "sys_platform == 'linux'"},
]

[package.extras]
feat = ["libb"]

[package.dev-dependencies]
pytest = "^7.0"

[[package]]
name = "liba"
version = "1.0.0"
"#;
    let mut got = edges(text, Format::PoetryLock);
    got.sort();
    assert_eq!(
        got,
        vec![
            ("app".to_string(), "liba".to_string()),
            ("app".to_string(), "libb".to_string()),
            ("app".to_string(), "libc".to_string()),
            ("app".to_string(), "pytest".to_string()),
        ]
    );
}

#[test]
fn go_mod_requires() {
    let text = r#"module example.com/m

go 1.21

require github.com/e/f v1.0.0

require (
	github.com/a/b v1.2.3 // indirect
	github.com/c/d v0.1.0
)

replace github.com/a/b => ../local/b
exclude github.com/x/y v1.0.0
"#;
    assert_eq!(
        edges(text, Format::GoMod),
        vec![
            ("example.com/m".to_string(), "github.com/a/b".to_string()),
            ("example.com/m".to_string(), "github.com/c/d".to_string()),
            ("example.com/m".to_string(), "github.com/e/f".to_string()),
        ]
    );
}

#[test]
fn go_mod_rejects_prefix_words() {
    // `modulex`/`requirex` must not be treated as directives.
    let text = "modulex v1\nrequirex y\n";
    assert!(strand_import::parse(text, Format::GoMod).is_err());
}

#[test]
fn package_lock_v3_nested_resolution() {
    let text = r#"{
  "name": "root",
  "lockfileVersion": 3,
  "packages": {
    "": {"name": "root", "dependencies": {"a": "^1.0.0"}},
    "node_modules/a": {"version": "1.0.0", "dependencies": {"b": "^2.0.0"}},
    "node_modules/b": {"version": "1.0.0"},
    "node_modules/a/node_modules/b": {"version": "2.0.0"}
  }
}"#;
    // a's dep b resolves to the nested v2 (nearest node_modules wins);
    // two installed versions means both nodes are name@version.
    assert_eq!(
        edges(text, Format::NpmLock),
        vec![
            ("a".to_string(), "b@2.0.0".to_string()),
            ("root".to_string(), "a".to_string()),
        ]
    );
}

#[test]
fn package_lock_duplicate_versions_disambiguated() {
    // Same package installed at two versions (e.g. debug@2 nested under
    // express + debug@4 at top level) must not collapse into one node.
    let text = r#"{
  "name": "root",
  "lockfileVersion": 3,
  "packages": {
    "": {"name": "root", "dependencies": {"express": "^4.0.0"}},
    "node_modules/express": {"version": "4.0.0", "dependencies": {"debug": "^2.0.0"}},
    "node_modules/express/node_modules/debug": {"version": "2.6.9"},
    "node_modules/debug": {"version": "4.4.3", "dependencies": {"ms": "^2.1.0"}},
    "node_modules/ms": {"version": "2.1.3"}
  }
}"#;
    // ms is installed once so it keeps its bare name; the two debug
    // installs become debug@2.6.9 / debug@4.4.3.
    assert_eq!(
        edges(text, Format::NpmLock),
        vec![
            ("debug@4.4.3".to_string(), "ms".to_string()),
            ("express".to_string(), "debug@2.6.9".to_string()),
            ("root".to_string(), "express".to_string()),
        ]
    );
}

#[test]
fn package_lock_v1_tree() {
    let text = r#"{
  "name": "root",
  "lockfileVersion": 1,
  "dependencies": {
    "a": {"version": "1.0.0", "dependencies": {"b": {"version": "2.0.0"}}},
    "c": {"version": "1.0.0"}
  }
}"#;
    assert_eq!(
        edges(text, Format::NpmLock),
        vec![
            ("a".to_string(), "b".to_string()),
            ("root".to_string(), "a".to_string()),
            ("root".to_string(), "c".to_string()),
        ]
    );
}

#[test]
fn pom_xml_project_and_deps() {
    let text = r#"<?xml version="1.0"?>
<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
  <parent>
    <groupId>com.example</groupId>
    <artifactId>parent</artifactId>
    <version>1</version>
  </parent>
  <artifactId>child</artifactId>
  <dependencies>
    <dependency>
      <groupId>junit</groupId>
      <artifactId>junit</artifactId>
      <version>4.13</version>
      <scope>test</scope>
    </dependency>
    <dependency>
      <artifactId>lib</artifactId>
      <version>1.0</version>
    </dependency>
  </dependencies>
  <dependencyManagement>
    <dependencies>
      <dependency>
        <groupId>mgmt</groupId>
        <artifactId>dep</artifactId>
      </dependency>
    </dependencies>
  </dependencyManagement>
</project>"#;
    assert_eq!(
        edges(text, Format::Pom),
        vec![
            (
                "com.example:child".to_string(),
                "com.example:lib".to_string()
            ),
            ("com.example:child".to_string(), "junit:junit".to_string()),
        ]
    );
}

#[test]
fn detect_format_by_filename() {
    use std::path::Path;
    assert_eq!(
        strand_import::detect_format(Path::new("Cargo.lock"), ""),
        Format::CargoLock
    );
    assert_eq!(
        strand_import::detect_format(Path::new("package-lock.json"), ""),
        Format::NpmLock
    );
    assert_eq!(
        strand_import::detect_format(Path::new("poetry.lock"), ""),
        Format::PoetryLock
    );
    assert_eq!(
        strand_import::detect_format(Path::new("go.mod"), ""),
        Format::GoMod
    );
    assert_eq!(
        strand_import::detect_format(Path::new("pom.xml"), ""),
        Format::Pom
    );
    // Content sniff for renamed files.
    assert_eq!(
        strand_import::detect_format(Path::new("foo.txt"), "module example.com/x\n"),
        Format::GoMod
    );
    assert_eq!(
        strand_import::detect_format(
            Path::new("foo.txt"),
            "{\"lockfileVersion\": 3, \"packages\": {}}"
        ),
        Format::NpmLock
    );
}
